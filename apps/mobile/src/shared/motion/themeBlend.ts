/**
 * Доля «ночного» цвета для текста при смене темы.
 *
 * NOTE: Фон темнеет плавно всю секунду. Если бы текст светлел так же плавно,
 * в середине перехода он совпал бы с фоном по яркости и на мгновение исчез.
 * Поэтому текст держит дневной цвет почти до середины и быстро переключается
 * около неё: контраст остаётся читаемым в любой момент заката.
 */
export function textBlend(night: number): number {
  'worklet';
  const t = Math.min(1, Math.max(0, (night - 0.4) / 0.2));
  return t * t * (3 - 2 * t);
}
